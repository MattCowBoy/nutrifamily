/** Normalizza il nome famiglia → email fittizia per Firebase Auth */
export function nameToEmail(name: string): string {
  const slug = name
    .toLowerCase()
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '') || 'famiglia';
  return `${slug}@nutrifamily.local`;
}
